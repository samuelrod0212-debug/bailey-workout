// Builds the installable web app (PWA) into docs/, which GitHub Pages serves.
// Usage: npm run build:pwa   then commit docs/ and push.
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, 'docs');
const BG = '#07080A';

fs.rmSync(out, { recursive: true, force: true });
execSync(`npx expo export --platform web --output-dir docs`, { cwd: root, stdio: 'inherit', env: { ...process.env, CI: '1' } });

// Icons (generated from assets/icon.png with sips-free pure copy; sizes are pre-rendered in assets/pwa/)
fs.mkdirSync(path.join(out, 'icons'), { recursive: true });
for (const f of fs.readdirSync(path.join(root, 'assets/pwa'))) fs.copyFileSync(path.join(root, 'assets/pwa', f), path.join(out, 'icons', f));

// Manifest
fs.writeFileSync(path.join(out, 'manifest.webmanifest'), JSON.stringify({
  name: 'Core', short_name: 'Core', description: "Bailey's training", start_url: './', scope: './',
  display: 'standalone', orientation: 'portrait', background_color: BG, theme_color: BG,
  icons: [
    { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
    { src: 'icons/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
}, null, 2));

// GitHub Pages: don't run Jekyll (it would hide the _expo folder)
fs.writeFileSync(path.join(out, '.nojekyll'), '');

// index.html: iPhone home-screen app tags + service worker
const indexPath = path.join(out, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');
html = html.replace(/<meta name="viewport"[^>]*>/, '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">');
html = html.replace(/<meta name="theme-color"[^>]*>/g, '');
html = html.replace('</head>', `
  <meta name="theme-color" content="${BG}">
  <meta name="robots" content="noindex,nofollow">
  <meta name="apple-mobile-web-app-capable" content="yes">
  <meta name="mobile-web-app-capable" content="yes">
  <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
  <meta name="apple-mobile-web-app-title" content="Core">
  <link rel="manifest" href="manifest.webmanifest">
  <link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
  <style>html,body{background:${BG};overscroll-behavior:none;-webkit-tap-highlight-color:transparent}</style>
</head>`);
html = html.replace('</body>', `<script>if('serviceWorker' in navigator){addEventListener('load',()=>navigator.serviceWorker.register('sw.js').catch(()=>{}))}</script>\n</body>`);
fs.writeFileSync(indexPath, html);

// Service worker: cache every file so the app opens offline. The version is a hash of the build,
// so phones pick up a new version automatically after each push.
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p); else if (!['sw.js', '.nojekyll', 'metadata.json'].includes(e.name)) files.push(path.relative(out, p).split(path.sep).join('/'));
  }
})(out);
const hash = crypto.createHash('sha1');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(out, f)));
const version = hash.digest('hex').slice(0, 10);
fs.writeFileSync(path.join(out, 'sw.js'), `// Generated by scripts/build-pwa.mjs. Offline cache for the home-screen app.
const CACHE = 'core-${version}';
const FILES = ${JSON.stringify(['./', ...files])};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
// Cache first so it opens instantly and offline; refresh in the background when online.
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.open(CACHE).then(async c => {
    const hit = await c.match(e.request, { ignoreSearch: true });
    const net = fetch(e.request).then(r => { if (r.ok) c.put(e.request, r.clone()); return r; }).catch(() => hit);
    return hit || net;
  }));
});
`);
console.log(`PWA built in docs/ (${files.length} files, version ${version})`);
