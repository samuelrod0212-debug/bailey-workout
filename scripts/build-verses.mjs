// Builds src/data/verses.ts from scripts/verse-references.txt using the
// public-domain World English Bible (npm package "world-english-bible").
// Usage: node scripts/build-verses.mjs <path-to-world-english-bible/json>
import fs from 'node:fs';
import path from 'node:path';

const jsonDir = process.argv[2];
if (!jsonDir) { console.error('Pass the path to the WEB json folder'); process.exit(1); }
const root = path.dirname(new URL(import.meta.url).pathname);
const refs = fs.readFileSync(path.join(root, 'verse-references.txt'), 'utf8')
  .split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('#'));

const cache = {};
function verseText(bookKey, ch, v) {
  cache[bookKey] ??= JSON.parse(fs.readFileSync(path.join(jsonDir, bookKey + '.json'), 'utf8'));
  const parts = cache[bookKey].filter(e => e.chapterNumber === ch && e.verseNumber === v && typeof e.value === 'string');
  return parts.map(p => p.value).join(' ');
}
const clean = s => s.replace(/\s+/g, ' ').replace(/\s([,.;:!?’”])/g, '$1').trim();

const seen = new Set(); const covered = new Set(); const out = []; const bad = []; const skipped = [];
for (const ref of refs) {
  const m = ref.match(/^(.+?) (\d+):(\d+)(?:-(\d+))?$/);
  if (!m) { bad.push(ref); continue; }
  const [, book, c, a, b] = m;
  if (seen.has(ref)) continue; seen.add(ref);
  if (!b && covered.has(ref)) continue; // already included as part of an earlier passage
  const key = book.toLowerCase().replace(/\s+/g, '');
  let text = '';
  let end = +(b ?? a);
  for (let v = +a; v <= end; v++) text += ' ' + verseText(key, +c, v);
  text = clean(text);
  if (!text) { bad.push(ref); continue; }
  // If a verse stops mid-sentence, keep adding the next verse (up to 3 more) so it reads as a whole thought.
  while (!/[.!?’”)]$/.test(text) && end < +a + 3) {
    const next = clean(verseText(key, +c, end + 1));
    if (!next) break;
    end++; text = clean(text + ' ' + next);
  }
  if (text.length > 340 || !/[.!?’”)]$/.test(text)) { skipped.push(ref); continue; } // too long for the card, or still mid-sentence
  for (let v = +a; v <= end; v++) covered.add(`${book} ${c}:${v}`);
  const label = `${book === 'Psalms' ? 'Psalm' : book} ${c}:${a}${end > +a ? '-' + end : ''}`;
  out.push({ ref: label, text, start: `${book} ${c}:${a}` });
}
if (bad.length) { console.error('Could not resolve:', bad); process.exit(1); }
if (out.length < 366) { console.error(`Only ${out.length} verses; need at least 366 (leap years).`); process.exit(1); }

const body = `// GENERATED by scripts/build-verses.mjs — edit scripts/verse-references.txt and re-run.
// Translation: World English Bible (WEB), public domain.
// The Home screen shows VERSES[dayOfYear - 1], so each verse appears once per year.
export type Verse = { ref: string; text: string };
export const VERSE_TRANSLATION = 'WEB';
export const VERSES: Verse[] = ${JSON.stringify(out.map(({ ref, text }) => ({ ref, text })), null, 2)};
`;
fs.mkdirSync(path.join(root, '../src/data'), { recursive: true });
fs.writeFileSync(path.join(root, '../src/data/verses.ts'), body);
if (skipped.length) console.log('Skipped (too long or incomplete):', skipped.join(', '));
console.log(`Wrote ${out.length} verses`);
